const MONTHS = ['Jan', 'Feb', 'Mar', 'Apr', 'May', 'Jun', 'Jul', 'Aug', 'Sep', 'Oct', 'Nov', 'Dec'];

// 'YYYY-MM-DD' → 'Feb 24, 2025' · 'YYYY-MM' → 'Feb 2025' · 'YYYY' → '2025'
export function fmtLaunch(d) {
  const [y, m, day] = d.split('-');
  if (!m) return y;
  return day ? `${MONTHS[m - 1]} ${+day}, ${y}` : `${MONTHS[m - 1]} ${y}`;
}
